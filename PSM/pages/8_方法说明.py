from __future__ import annotations

import streamlit as st


st.title("方法说明")
st.caption("说明当前版本的方法依据、适用范围和局限。")

st.markdown(
    """
## 当前版本采用的方法

- 数据清洗：正则表达式去 URL、去空、去重、长度统计。
- 中文分词：Jieba 分词 + 停用词过滤。
- 关键词：词频统计与 TF-IDF。
- 观点聚类：TF-IDF 向量 + K-means。
- 情感分析：轻量情感词典，输出正向、中性、负向。
- 立场检测：围绕目标对象的规则词典判断。
- 不确定信息：识别“网传、据说、求证、未证实”等表达。
- 风险评分：负面情绪、热度增长、主题集中度、反对立场、不确定信息、极端表达和互动放大系数的加权评分。

## 后续增强方向

- 接入 SBERT，提高语义相似文本聚类质量。
- 接入 BERTopic，生成更可解释的主题结构。
- 接入 BERT 情感模型，提高复杂语境下的情感识别能力。
- 美化 Word/PDF 报告，补充作品集展示页。

## 文献如何支撑本项目

- BERT-LDA 舆情情感演化研究提示：舆情分析要把事件阶段、主题演化和情感变化结合起来，因此系统保留时间字段、热度走势和情感演化入口。
- LDA 与网络文本分析相关研究提示：高频词、TF-IDF、主题模型和聚类可以共同解释“大家在讨论什么”，因此系统设置“主题观点”页面。
- BERTopic 与 SBERT 相关研究提示：语义向量能改善传统词袋模型的语义缺失，因此它们被规划为后续增强模块。
- 社交媒体事件摘要研究提示：社交媒体文本噪声和重复较多，需要清洗、代表评论抽取和结构化摘要，因此系统设置报告生成模块。
- 立场检测综述提示：立场必须绑定目标对象，不能和情感分析混为一谈，因此系统单独设置目标对象输入。
- 谣言检测综述提示：轻量系统不宜直接判断真假，因此第一版只识别“网传、求证、未证实”等不确定表达。
- 群体极化风险研究提示：风险来自情绪、互动、信息属性和主体回应等多因素耦合，因此系统采用多指标加权风险评分。

完整文献笔记已整理在 `docs/literature_notes.md`。

## 方法局限

第一版结果适合辅助分析和课堂展示，不应被解释为现实风险预测或事实真伪判断。模型结果会受到样本来源、文本质量、词典覆盖、平台语境和数据量影响。
"""
)
